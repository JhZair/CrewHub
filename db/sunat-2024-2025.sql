   el `on conflict do nothing` de arriba no las toca. Se corrige la
   procedencia: el dato era correcto, lo que faltaba era poder decir de dónde
   salía. */
update vencimiento_oficial
   set fuente = 'Cronograma SUNAT 2025 (ww3.sunat.gob.pe/cl-ti-itcronobligme) · cotejado con la tabla del equipo'
 where clase = 'igv_renta' and anio = 2025 and digito = 8
   and fuente like '%SeaTable%';

-- Rellena los periodos que se hayan creado sin fecha. No pisa los de a mano.
select public.obligaciones_generar_todas() as periodos_nuevos;

-- ── VERIFICAR ──
select anio, count(*) as filas, count(distinct mes) as meses,
       count(distinct digito) as digitos, min(fecha) as primera, max(fecha) as ultima
  from vencimiento_oficial
 where clase = 'igv_renta'
 group by anio order by anio;

-- Ninguna debería salir: SUNAT no vence en fin de semana.
select anio, mes, digito, fecha, trim(to_char(fecha, 'Day')) as dia
  from vencimiento_oficial
 where extract(isodow from fecha) > 5;

-- Y los periodos que sigan sin fecha, si queda alguno.
select o.clase, p.anio, count(*) as sin_fecha
  from obligacion_periodo p join obligacion o on o.id = p.obligacion_id
 where p.vence is null group by 1, 2 order by 2;
